def glyph_bytes(ch):
    rows = G[ch]
    out = []
    for r in rows:                      # 7 rows, each doubled -> 14
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= 0x80 >> (i + 1)     # 5 px centered in 8 (cols 1..5)
        out.append(b)
        out.append(b)
    out.append(0)                        # row 14
    out.append(0)                        # row 15
    return out                           # 16 bytes

def main():
    print("\\ font8x16: 8x16 1bpp font, ASCII 32..126, MSB-left, generated by tools/mkfont.py")
    print("\\ packed 4 bytes/cell, little-endian (c@ on the cell array yields the bytes)")
    print("create font8x16")
    data = []
    for code in range(32, 127):
        data.extend(glyph_bytes(chr(code)))
    assert len(data) % 4 == 0
    cells = [data[i] | data[i+1] << 8 | data[i+2] << 16 | data[i+3] << 24
             for i in range(0, len(data), 4)]
    for i in range(0, len(cells), 8):
        print("  " + " ".join("%d ," % c for c in cells[i:i+8]))

if __name__ == "__main__":
    main()
